from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol
from uuid import UUID


@dataclass(frozen=True)
class FavoriteRecord:
    reading_id: UUID
    created_at: datetime

    def dto(self):
        return {'reading_id': str(self.reading_id), 'created_at': self.created_at.isoformat()}


@dataclass(frozen=True)
class FavoriteRequest:
    fingerprint: str
    reading_id: UUID | None
    created_at: datetime


class FavoritesRepository(Protocol):
    def lock(self, owner: UUID) -> None: ...
    def active(self, owner: UUID) -> None: ...
    def has_reading(self, owner: UUID, reading_id: UUID) -> bool: ...
    def request(self, owner: UUID, key_hash: str) -> FavoriteRequest | None: ...
    def remember(self, owner: UUID, key_hash: str, fingerprint: str, favorite: FavoriteRecord) -> None: ...
    def get(self, owner: UUID, reading_id: UUID) -> FavoriteRecord | None: ...
    def add(self, owner: UUID, reading_id: UUID) -> FavoriteRecord: ...
    def remove(self, owner: UUID, reading_id: UUID) -> bool: ...
    def list(self, owner: UUID, *, after: tuple[datetime, UUID] | None, limit: int) -> list[FavoriteRecord]: ...
    def all_owned(self, owner: UUID) -> list[FavoriteRecord]: ...
    def erase_owner(self, owner: UUID) -> None: ...


class FavoritesUnitOfWork(Protocol):
    favorites: FavoritesRepository

    def repository_for(self, transaction: object) -> FavoritesRepository: ...
    def __enter__(self) -> 'FavoritesUnitOfWork': ...
    def __exit__(self, *exc: object) -> None: ...
    def commit(self) -> None: ...
