from typing import Protocol, Any
from api.domain.billing import Product, StorePurchase


class PurchaseVerifier(Protocol):
    def available(self) -> bool: ...
    def verify(self, product: Product, token: str) -> StorePurchase: ...
    def acknowledge(self, product: Product, token: str) -> None: ...


class ReceiptCipher(Protocol):
    def available(self) -> bool: ...
    def seal(self, value: str) -> str: ...
    def open(self, value: str) -> str: ...


class BillingUnitOfWork(Protocol):
    connection: Any
    receipts: Any
    def __enter__(self) -> 'BillingUnitOfWork': ...
    def __exit__(self, *exc: object) -> None: ...
    def commit(self) -> None: ...
