from typing import Protocol
from uuid import UUID


class JournalInsightsRepository(Protocol):
    transaction: object
    def lock_owner(self, owner: UUID) -> None: ...
    def owner_available(self, owner: UUID, guard=None) -> bool: ...
    def get(self, owner: UUID, insight_id: UUID) -> dict | None: ...
    def add(self, values: dict, sources: list[dict]) -> dict: ...
    def latest_consent(self, owner: UUID, kind: str) -> dict | None: ...
    def current_sources(self, owner: UUID, ids: list[UUID]) -> list[dict]: ...
    def mark_generating(self, owner, insight_id, version) -> bool: ...
    def mark_terminal(self, owner, insight_id, version, state) -> None: ...
    def complete(self, owner, insight_id, version, result) -> bool: ...
    def invalidate(self, owner, insight_id) -> None: ...
    def invalidate_for_journal(self, owner, entry_id) -> None: ...
    def invalidate_for_consent(self, owner, kind) -> None: ...
    def all_owned(self, owner) -> list[dict]: ...
    def erase_owner(self, owner) -> None: ...


class JournalInsightsUnitOfWork(Protocol):
    insights: JournalInsightsRepository
    def __enter__(self): ...
    def __exit__(self, *exc): ...
    def commit(self) -> None: ...
    def repository_for(self, transaction: object) -> JournalInsightsRepository: ...
