from typing import Protocol
from uuid import UUID


class Guidance(Protocol):
    def advise(self, topic: str, question: str, answers: list[bool], tone: str, context: list[dict]) -> dict: ...


class ExperienceRepository(Protocol):
    def lock(self, owner: UUID, kind: str, request_id: UUID) -> None: ...
    def operation(self, owner: UUID, kind: str, request_id: UUID) -> dict | None: ...
    def remember(self, owner: UUID, kind: str, request_id: UUID, fingerprint: str, result: dict) -> None: ...
    def save_reading(self, owner: UUID, entry_id: UUID, result: dict) -> dict: ...
    def save_counsel(self, owner: UUID, entry_id: UUID, result: dict, answers: list[bool], parent: UUID | None) -> dict: ...
    def list(self, owner: UUID, kind: str) -> list[dict]: ...
    def daily(self, owner: UUID, day: str, topic: str, result: dict) -> dict: ...
    def context(self, owner: UUID, parent: UUID) -> list[dict]: ...
    def ai_usage(self, owner: UUID) -> int: ...


class ExperienceUnitOfWork(Protocol):
    experiences: ExperienceRepository
    def __enter__(self): ...
    def __exit__(self, *args): ...
    def commit(self) -> None: ...
