from __future__ import annotations

from datetime import datetime
from typing import Protocol
from uuid import UUID

from api.domain.social_auth import VerifiedSocialIdentity


class SocialProvider(Protocol):
    def available(self, provider: str) -> bool: ...
    def authorization_url(self, provider: str, *, state: str, nonce: str, verifier: str) -> str: ...
    def exchange(self, provider: str, code: str, *, nonce_hash: str, verifier: str) -> VerifiedSocialIdentity: ...


class SocialRepository(Protocol):
    def lock_owner(self, owner: UUID) -> None: ...
    def active(self, owner: UUID) -> None: ...
    def purge(self, now: datetime) -> None: ...
    def flow_count(self, owner: UUID, now: datetime) -> int: ...
    def add_flow(self, row: dict) -> None: ...
    def flow(self, state_hash: str) -> dict | None: ...
    def claim_flow(self, state_hash: str, provider: str, now: datetime) -> dict | None: ...
    def complete_flow(self, state_hash: str, subject_hash: str, ticket_hash: str, expires_at: datetime) -> bool: ...
    def discard_flow(self, state_hash: str) -> None: ...
    def ticket(self, owner: UUID, ticket_hash: str, now: datetime) -> dict | None: ...
    def lock_identity(self, provider: str, subject_hash: str) -> None: ...
    def identity_owner(self, provider: str, subject_hash: str) -> UUID | None: ...
    def member(self, owner: UUID) -> bool: ...
    def has_provider(self, owner: UUID, provider: str) -> bool: ...
    def link_identity(self, owner: UUID, provider: str, subject_hash: str) -> None: ...
    def providers(self, owner: UUID) -> list[str]: ...
    def capture_legacy_session(self, owner: UUID) -> None: ...
    def add_session(self, row: dict) -> None: ...
    def session_by_hash(self, token_hash: str) -> dict | None: ...
    def renew(self, session_id: UUID, expires_at: datetime) -> None: ...
    def list_sessions(self, owner: UUID) -> list[dict]: ...
    def revoke(self, owner: UUID, session_id: UUID, now: datetime) -> bool: ...
    def revoke_all(self, owner: UUID, now: datetime) -> None: ...
    def export_owner(self, owner: UUID) -> dict: ...
    def erase_owner(self, owner: UUID) -> None: ...


class SocialUnitOfWork(Protocol):
    social: SocialRepository
    def repository_for(self, transaction: object) -> SocialRepository: ...
    def __enter__(self) -> SocialUnitOfWork: ...
    def __exit__(self, *exc): ...
    def commit(self) -> None: ...
