from typing import Protocol
from uuid import UUID


class StoryRepository(Protocol):
    def lock(self, owner: UUID) -> None: ...
    def active(self, owner: UUID) -> None: ...
    def request(self, owner: UUID, key_hash: str) -> dict | None: ...
    def remember(self, owner: UUID, key_hash: str, fingerprint: str, run_id: UUID) -> None: ...
    def get(self, owner: UUID, run_id: UUID) -> dict | None: ...
    def latest(self, owner: UUID, episode_id: str) -> dict | None: ...
    def create(self, owner: UUID, run_id: UUID, values: dict) -> dict: ...
    def save(self, owner: UUID, run_id: UUID, expected: int, values: dict) -> dict | None: ...
    def all_owned(self, owner: UUID) -> list[dict]: ...
    def erase_owner(self, owner: UUID) -> None: ...


class StoryUnitOfWork(Protocol):
    story: StoryRepository
    def repository_for(self, transaction: object) -> StoryRepository: ...
    def __enter__(self) -> 'StoryUnitOfWork': ...
    def __exit__(self, *exc: object) -> None: ...
    def commit(self) -> None: ...
