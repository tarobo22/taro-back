from __future__ import annotations

from datetime import datetime
from typing import Protocol, Self
from uuid import UUID

from api.domain.identity import DeviceSession


class IdentityRepository(Protocol):
    def create(self, owner: UUID, token_hash: str, expires_at: datetime, platform: str,
               locale: str, timezone: str) -> None: ...
    def find(self, token_hash: str) -> DeviceSession | None: ...
    def get(self, owner: UUID) -> DeviceSession | None: ...
    def renew(self, owner: UUID, expires_at: datetime) -> None: ...
    def lock(self, owner: UUID) -> None: ...


class IdentityUnitOfWork(Protocol):
    sessions: IdentityRepository
    def __enter__(self) -> Self: ...
    def __exit__(self, *exc) -> None: ...
    def commit(self) -> None: ...
