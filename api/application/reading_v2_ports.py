from __future__ import annotations

from dataclasses import dataclass
from datetime import date, datetime
from typing import Callable, Protocol
from uuid import UUID


class ReadingCatalog(Protocol):
    def get_deck(self, deck_id) -> dict: ...
    def list_cards(self, *, deck_version_id=None) -> dict: ...


@dataclass(frozen=True)
class ReadingRecord:
    """Persistence-independent reading state and its public projection."""
    id: UUID
    kind: str
    state: str
    version: int
    deck_version_id: UUID
    private_slots: list[dict]
    selected_cards: list[dict]
    created_at: datetime
    view: dict


@dataclass(frozen=True)
class DailyAnchor:
    card_id: int
    deck_version_id: UUID
    captured_timezone: str


@dataclass(frozen=True)
class ReadingCommand:
    fingerprint: str
    reading_id: UUID | None


class ReadingRepository(Protocol):
    # This opaque token is only passed to existing cross-context callbacks.
    transaction: object

    def lock_owner(self, owner: UUID) -> None: ...
    def owner_available(self, owner: UUID, guard: Callable | None = None) -> bool: ...
    def timezone(self, owner: UUID) -> str | None: ...
    def get(self, owner: UUID, reading_id: UUID) -> ReadingRecord | None: ...
    def command(self, owner: UUID, scope: str, key: UUID, now: datetime) -> ReadingCommand | None: ...
    def discard_command(self, owner: UUID, scope: str, key: UUID) -> None: ...
    def remember(self, owner: UUID, scope: str, key: UUID, fingerprint: str,
                 reading_id: UUID, expires_at: datetime) -> None: ...
    def find_daily(self, owner: UUID, day: date, topic: str) -> ReadingRecord | None: ...
    def daily_anchor(self, owner: UUID, day: date, topic: str) -> DailyAnchor | None: ...
    def add_daily_anchor(self, owner: UUID, day: date, topic: str, card_id: int,
                         deck_version_id, timezone: str, expires_at: datetime) -> DailyAnchor: ...
    def add(self, owner: UUID, reading_id: UUID, *, kind: str, topic: str, question: str,
            deck_version_id, local_day: date | None, captured_timezone: str, state: str,
            private_slots: list[dict], selected_cards: list[dict]) -> ReadingRecord: ...
    def shuffle(self, owner: UUID, reading_id: UUID, version: int, slots: list[dict]) -> ReadingRecord | None: ...
    def select(self, owner: UUID, reading_id: UUID, version: int, cards: list[dict]) -> ReadingRecord | None: ...
    def delete(self, owner: UUID, reading_id: UUID) -> None: ...
    def list(self, owner: UUID, *, limit: int, after=None, kind=None, topic=None) -> list[ReadingRecord]: ...
    def snapshot(self, owner: UUID, reading_id: UUID) -> dict | None: ...
    def mark_generating(self, owner: UUID, reading_id: UUID, version: int) -> bool: ...
    def mark_failed(self, owner: UUID, reading_id: UUID, version: int) -> None: ...
    def complete(self, owner: UUID, reading_id: UUID, version: int, result: dict) -> bool: ...
    def exists(self, owner: UUID, reading_id: UUID) -> bool: ...
    def all_owned(self, owner: UUID) -> list[ReadingRecord]: ...
    def owned_ids(self, owner: UUID) -> list[UUID]: ...
    def erase_owner(self, owner: UUID) -> None: ...
    def purge_expired(self, now: datetime) -> int: ...


class ReadingUnitOfWork(Protocol):
    readings: ReadingRepository
    def repository_for(self, transaction: object) -> ReadingRepository: ...
    def __enter__(self): ...
    def __exit__(self, *exc): ...
    def commit(self): ...
