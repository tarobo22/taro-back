from typing import Callable, Protocol, Self
from uuid import UUID

from api.domain.journal import JournalEntry


class JournalRepository(Protocol):
    def add(self, entry: JournalEntry) -> JournalEntry: ...
    def add_once(self, entry: JournalEntry, request_id: UUID) -> JournalEntry: ...
    def get(self, owner_id: UUID, entry_id: UUID) -> JournalEntry | None: ...
    def list(self, owner_id: UUID) -> list[JournalEntry]: ...
    def update(self, entry: JournalEntry) -> JournalEntry: ...
    def delete(self, owner_id: UUID, entry_id: UUID) -> bool: ...


class JournalUnitOfWork(Protocol):
    journals: JournalRepository

    def guard_owner(self, owner_id: UUID, callback: Callable[[object, UUID], bool | None] | None) -> None: ...

    def __enter__(self) -> Self: ...
    def __exit__(self, *exc: object) -> None: ...
    def commit(self) -> None: ...
