from typing import Protocol
from uuid import UUID


class ReadingSource(Protocol):
    """Methods run inside the caller's owner-locked transaction."""
    def snapshot(self, connection, owner: UUID, reading_id: UUID) -> dict: ...
    def validate(self, connection, owner: UUID, reading_id: UUID, version: int) -> bool: ...
    def complete(self, connection, owner: UUID, reading_id: UUID, version: int, result: dict) -> bool: ...


class AIProvider(Protocol):
    def available(self) -> bool: ...
    def generate(self, payload: dict) -> dict: ...


class TranscriptionProvider(Protocol):
    def available(self) -> bool: ...
    def transcribe(self, path, mime_type: str) -> str: ...
