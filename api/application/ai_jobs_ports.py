from typing import Callable, Protocol
from uuid import UUID


class ReadingSource(Protocol):
    """Methods run inside the caller's owner-locked transaction."""
    def snapshot(self, connection, owner: UUID, reading_id: UUID) -> dict: ...
    def validate(self, connection, owner: UUID, reading_id: UUID, version: int) -> bool: ...
    def complete(self, connection, owner: UUID, reading_id: UUID, version: int, result: dict) -> bool: ...
    def mark_generating(self, connection, owner: UUID, reading_id: UUID, version: int) -> bool: ...
    def mark_failed(self, connection, owner: UUID, reading_id: UUID, version: int) -> None: ...


class AIProvider(Protocol):
    def available(self) -> bool: ...
    def generate(self, payload: dict) -> dict: ...


class TranscriptionProvider(Protocol):
    def available(self) -> bool: ...
    def transcribe(self, path, mime_type: str) -> str: ...


class AudioStore(Protocol):
    def validate(self, data: bytes, mime_type: str, duration_ms: int,
                 max_bytes: int, max_duration_ms: int) -> tuple[str, int]: ...
    def save(self, data: bytes, mime_type: str) -> str: ...
    def delete(self, path: str) -> None: ...
    def purge(self, age_seconds: int) -> int: ...


class AIJobsRepository(Protocol):
    """Persistence port returning snapshots; transaction is opaque to orchestration.

    An adapter binds all operations to one transaction. Projection methods translate
    persistence values into the existing public contract without leaking driver rows.
    """
    transaction: object
    def lock_owner(self, owner: UUID) -> None: ...
    def owner_available(self, owner: UUID, guard: Callable | None = None) -> bool: ...
    def idempotency(self, owner, scope, key) -> dict | None: ...
    def remember(self, owner, scope, key, fingerprint, resource, response) -> None: ...
    def latest_consent(self, owner, kind) -> dict | None: ...
    def add_consent(self, event_id, owner, kind, policy_version, granted) -> dict: ...
    def pending_for_consent(self, owner, kind) -> list[dict]: ...
    def consents(self, owner, after, limit) -> list[dict]: ...
    def consent_view(self, snapshot) -> dict: ...
    def consent_cursor(self, snapshot) -> list: ...
    def add_conversation(self, conversation_id, owner, topic, tone) -> dict: ...
    def conversation(self, owner, conversation_id) -> dict | None: ...
    def conversations(self, owner, after, limit) -> list[dict]: ...
    def conversation_view(self, snapshot) -> dict: ...
    def conversation_cursor(self, snapshot) -> list: ...
    def close_conversation(self, owner, conversation_id) -> dict: ...
    def pending_for_conversation(self, owner, conversation_id) -> list[dict]: ...
    def delete_conversation(self, owner, conversation_id) -> None: ...
    def journal(self, owner, entry_id) -> dict | None: ...
    def journal_version(self, owner, entry_id) -> int | None: ...
    def active_job_exists(self, owner) -> bool: ...
    def lock_usage(self) -> None: ...
    def usage(self, owner) -> dict: ...
    def add_job(self, values: dict) -> dict: ...
    def reserve_usage(self, job_id, owner) -> None: ...
    def add_source(self, job_id, entry_id, version) -> None: ...
    def duplicate_turn(self, owner, conversation_id, message_id) -> dict | None: ...
    def latest_job(self, owner, resource) -> dict | None: ...
    def next_turn_index(self, conversation_id) -> int: ...
    def add_turn(self, values: dict) -> None: ...
    def turn(self, owner, turn_id, conversation=None) -> dict | None: ...
    def turns(self, owner, conversation_id, after, limit) -> list[dict]: ...
    def turn_view(self, snapshot) -> dict: ...
    def set_turn_state(self, owner, turn_id, state, result=None, advance_version=False) -> None: ...
    def job(self, owner, job_id, for_update=False) -> dict | None: ...
    def job_view(self, snapshot) -> dict: ...
    def accepted(self, snapshot) -> dict: ...
    def cancel_job(self, job_id, state) -> None: ...
    def context_sources(self, job_id) -> list[dict]: ...
    def history(self, owner, conversation_id, before, limit) -> list[dict]: ...
    def finish_job(self, job_id, state, code, url) -> None: ...
    def claim_next(self, lease_id, seconds) -> dict | None: ...
    def mark_provider_started(self, job_id, lease_id, started) -> None: ...
    def add_run(self, values: dict) -> None: ...
    def heartbeat(self, job_id, lease_id, seconds) -> bool: ...
    def recovery_candidates(self) -> list[dict]: ...
    def expired_job(self, job_id) -> dict | None: ...
    def requeue(self, job_id) -> None: ...
    def pending_for_resource(self, owner, resource) -> list[dict]: ...
    def pending_for_journal(self, owner, entry_id) -> list[dict]: ...
    def audio_path(self, transcription_id) -> str | None: ...
    def detach_audio(self, transcription_id) -> None: ...
    def add_transcription(self, resource, owner, path, mime, duration, seconds) -> None: ...
    def transcription(self, owner, resource, live_only=False) -> dict | None: ...
    def transcription_view(self, snapshot) -> dict: ...
    def set_transcription_state(self, resource, state, transcript=None, advance_version=False, keep_deleted=False) -> None: ...
    def forget_resource_commands(self, owner, resource) -> None: ...
    def expired_transcriptions(self) -> list[dict]: ...
    def transcriptions(self, owner) -> list[dict]: ...
    def erase_owner(self, owner) -> None: ...
    def export_owner(self, owner) -> dict: ...
    def turn_exists(self, owner, turn_id) -> bool: ...


class AIJobsUnitOfWork(Protocol):
    ai_jobs: AIJobsRepository
    def __enter__(self): ...
    def __exit__(self, *exc): ...
    def commit(self) -> None: ...
    def repository_for(self, transaction: object) -> AIJobsRepository: ...
